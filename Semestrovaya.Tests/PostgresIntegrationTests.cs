using Npgsql;
using Semestrovaya.Models;
using Semestrovaya.ORM;

namespace Semestrovaya.Tests;

public class PostgresIntegrationTests
{
    [PostgresFact]
    public async Task CrudPersistsValuesAndHonorsForeignKeys()
    {
        string schema = "audit_" + Guid.NewGuid().ToString("N");
        string connectionString = Environment.GetEnvironmentVariable(PostgresFactAttribute.ConnectionVariable)!;
        await using var rootSource = NpgsqlDataSource.Create(connectionString);
        await using var root = await rootSource.OpenConnectionAsync();
        await using var createSchema = new NpgsqlCommand($"CREATE SCHEMA {schema}", root);
        await createSchema.ExecuteNonQueryAsync();

        try
        {
            var testConnection = new NpgsqlConnectionStringBuilder(connectionString) { SearchPath = schema };
            await using var source = NpgsqlDataSource.Create(testConnection.ConnectionString);
            await using (var connection = await source.OpenConnectionAsync())
            {
                await using var tables = new NpgsqlCommand("""
                    CREATE TABLE categories (
                        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name text NOT NULL, description text NOT NULL, sort_order integer NOT NULL
                    );
                    CREATE TABLE cards (
                        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        category_id integer NOT NULL REFERENCES categories,
                        title text NOT NULL, description text NOT NULL, image_url text NOT NULL, card_type text NOT NULL
                    );
                    """, connection);
                await tables.ExecuteNonQueryAsync();
            }

            var db = new DbContext(source);
            int categoryId = await db.InsertAsync("categories", new Category
            {
                Name = "Тестовая категория", Description = "Описание", SortOrder = 1
            });
            var card = new Card
            {
                CategoryId = categoryId,
                Title = "Иллюстрация",
                ImageUrl = "/images/Avel.jpg",
                CardType = "Герой",
                Description = "Кавычка ' и новая строка\nВторая строка"
            };

            int id = await db.InsertAsync("cards", card);
            var stored = Assert.Single(await db.GetAllAsync<Card>("cards"));
            Assert.Equal(id, stored.Id);
            Assert.Equal(categoryId, stored.CategoryId);
            Assert.Equal(card.Description, stored.Description);

            card.Title = "Обновлённая карточка";
            Assert.Equal(1, await db.UpdateAsync("cards", id, card));
            Assert.Equal(card.Title, (await db.GetByIdAsync<Card>("cards", id))?.Title);

            card.CategoryId = categoryId + 1;
            var error = await Assert.ThrowsAsync<PostgresException>(() => db.UpdateAsync("cards", id, card));
            Assert.Equal(PostgresErrorCodes.ForeignKeyViolation, error.SqlState);

            Assert.Equal(1, await db.DeleteAsync("cards", id));
            Assert.Null(await db.GetByIdAsync<Card>("cards", id));
        }
        finally
        {
            await using var drop = new NpgsqlCommand($"DROP SCHEMA {schema} CASCADE", root);
            await drop.ExecuteNonQueryAsync();
        }
    }
}

public sealed class PostgresFactAttribute : FactAttribute
{
    public const string ConnectionVariable = "SEMESTROVAYA_TEST_POSTGRES";

    public PostgresFactAttribute()
    {
        if (string.IsNullOrWhiteSpace(Environment.GetEnvironmentVariable(ConnectionVariable)))
            Skip = $"Set {ConnectionVariable} to a dedicated PostgreSQL test database.";
    }
}
