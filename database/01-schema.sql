BEGIN;

CREATE TABLE IF NOT EXISTS categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE,
    description text NOT NULL,
    sort_order integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS cards (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id integer NOT NULL REFERENCES categories(id),
    title varchar(200) NOT NULL,
    description text NOT NULL,
    image_url varchar(255) NOT NULL,
    card_type varchar(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) NOT NULL UNIQUE,
    email varchar(255) NOT NULL UNIQUE,
    password_hash text NOT NULL,
    created_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    role varchar(10) NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin'))
);

CREATE TABLE IF NOT EXISTS favorites (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    card_id integer NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    note varchar(500) NOT NULL DEFAULT '',
    created_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    UNIQUE (user_id, card_id)
);

-- Apply to an existing local installation without replacing its data.
ALTER TABLE users ADD COLUMN IF NOT EXISTS role varchar(10) NOT NULL DEFAULT 'user'
    CHECK (role IN ('user', 'admin'));
ALTER TABLE favorites ADD COLUMN IF NOT EXISTS note varchar(500) NOT NULL DEFAULT '';
ALTER TABLE favorites ADD COLUMN IF NOT EXISTS updated_at timestamp;
UPDATE favorites SET updated_at = created_at WHERE updated_at IS NULL;
ALTER TABLE favorites ALTER COLUMN updated_at SET DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC');
ALTER TABLE favorites ALTER COLUMN updated_at SET NOT NULL;
CREATE INDEX IF NOT EXISTS cards_category_idx ON cards (category_id);
CREATE INDEX IF NOT EXISTS favorites_card_idx ON favorites (card_id);

COMMIT;
